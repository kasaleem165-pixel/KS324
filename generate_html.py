def risk_badge(r):
    r=str(r).strip()
    if r=="High":        return f'<span class="badge badge-high">High</span>'
    if r in("M to H",): return f'<span class="badge badge-mh">M to H</span>'
    if r in("L to M",): return f'<span class="badge badge-lm">L to M</span>'
    return f'<span class="badge badge-low">Low</span>'

def type_badge(t):
    if t=="Repeat": return '<span class="badge badge-repeat">Repeat</span>'
    return '<span class="badge badge-new">New</span>'

def count_risk(obs_list):
    c={"High":0,"M to H":0,"L to M":0,"Low":0}
    for row in obs_list:
        r=str(row[6]).strip()
        if r in c: c[r]+=1
    return c

